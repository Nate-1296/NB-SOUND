//! Tipo de error de dominio de NB Sound.
//!
//! Ningún error cruza el puente como cadena de texto: Rust devuelve códigos
//! canónicos estables y la interfaz los traduce. Es el mismo contrato que NB
//! Books (`NB_Books/src-tauri/src/error.rs`), y lo vigila
//! `scripts/check-error-contract.mjs`.

use serde::Serialize;
use ts_rs::TS;

/// Error de dominio. Cada variante tiene un código canónico estable que forma
/// parte del contrato con la interfaz: **renombrar un código es un cambio
/// incompatible**.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
pub enum NsError {
    #[error("el archivo solicitado no existe")]
    FileNotFound,

    #[error("la ruta queda fuera del ámbito permitido")]
    PathNotAllowed,

    #[error("el formato de audio no está soportado")]
    FormatUnsupported,

    #[error("el archivo de audio está dañado o incompleto")]
    AudioCorrupted,

    #[error("fallo de la capa de almacenamiento")]
    StorageFailure,

    #[error("la base de datos está en una versión distinta de la esperada")]
    SchemaMismatch,

    #[error("el componente solicitado no está disponible")]
    ComponentUnavailable,

    #[error("el modo sin red está activado")]
    NetworkDisabled,

    #[error("hace falta consentimiento para usar ese servicio")]
    ConsentRequired,

    #[error("la petición de red no se pudo completar")]
    NetworkFailure,

    /// Una descarga llegó entera pero no es lo que se esperaba: su SHA-256 no es
    /// el fijado. Nunca se instala (ADR-006).
    #[error("la descarga no coincide con su huella")]
    IntegrityMismatch,

    /// La función necesita un agregado que no está instalado. La interfaz no lo
    /// muestra como error: ofrece instalarlo ahí mismo (ADR-006).
    #[error("hace falta instalar un agregado")]
    AddonRequired,

    #[error("operación cancelada")]
    Cancelled,

    /// Un dato que el usuario escribió no vale: un nombre vacío o demasiado largo.
    #[error("el dato no es válido")]
    InvalidInput,

    /// Ya hay algo con ese nombre (una playlist, por ejemplo).
    #[error("el nombre ya está en uso")]
    NameTaken,

    #[error("error interno no clasificado")]
    Internal,
}

impl NsError {
    /// Código canónico. Es lo que la interfaz usa para elegir el mensaje; nunca se
    /// muestra tal cual.
    pub const fn code(&self) -> &'static str {
        match self {
            Self::FileNotFound => "FILE_NOT_FOUND",
            Self::PathNotAllowed => "PATH_NOT_ALLOWED",
            Self::FormatUnsupported => "FORMAT_UNSUPPORTED",
            Self::AudioCorrupted => "AUDIO_CORRUPTED",
            Self::StorageFailure => "STORAGE_FAILURE",
            Self::SchemaMismatch => "SCHEMA_MISMATCH",
            Self::ComponentUnavailable => "COMPONENT_UNAVAILABLE",
            Self::NetworkDisabled => "NETWORK_DISABLED",
            Self::ConsentRequired => "CONSENT_REQUIRED",
            Self::NetworkFailure => "NETWORK_FAILURE",
            Self::IntegrityMismatch => "INTEGRITY_MISMATCH",
            Self::AddonRequired => "ADDON_REQUIRED",
            Self::Cancelled => "CANCELLED",
            Self::InvalidInput => "INVALID_INPUT",
            Self::NameTaken => "NAME_TAKEN",
            Self::Internal => "INTERNAL",
        }
    }
}

/// Todas las variantes, en orden. La prueba de estabilidad y el generador de la
/// lista para la interfaz recorren esta tabla, nunca una muestra.
pub const TODAS: &[NsError] = &[
    NsError::FileNotFound,
    NsError::PathNotAllowed,
    NsError::FormatUnsupported,
    NsError::AudioCorrupted,
    NsError::StorageFailure,
    NsError::SchemaMismatch,
    NsError::ComponentUnavailable,
    NsError::NetworkDisabled,
    NsError::ConsentRequired,
    NsError::NetworkFailure,
    NsError::IntegrityMismatch,
    NsError::AddonRequired,
    NsError::Cancelled,
    NsError::InvalidInput,
    NsError::NameTaken,
    NsError::Internal,
];

/// Escribe la lista de códigos que consume la interfaz. El nombre empieza por
/// `export_bindings_` para que `pnpm check:bindings` la ejecute junto a los tipos
/// de `ts-rs` y compruebe que el árbol no queda sucio.
#[cfg(test)]
#[test]
#[allow(non_snake_case)]
fn export_bindings_errorcodes() {
    use std::fmt::Write as _;

    let mut ts = String::from(
        "// This file was generated by NB Sound from src-tauri/src/error.rs.\n\
         // Do not edit this file manually.\n\n\
         /** Los códigos de error canónicos que puede devolver el runtime. */\n\
         export const ERROR_CODES = [\n",
    );
    for variante in TODAS {
        let _ = writeln!(ts, "  '{}',", variante.code());
    }
    ts.push_str("] as const;\n\n/** Un código de error del runtime. */\n");
    ts.push_str("export type ErrorCode = (typeof ERROR_CODES)[number];\n");

    let destino =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/bindings/errorCodes.ts");
    std::fs::create_dir_all(destino.parent().expect("con carpeta")).expect("carpeta de bindings");
    std::fs::write(destino, ts).expect("no se pudieron escribir los códigos de error");
}

/// Forma serializada que cruza el puente. Solo el código: el mensaje de una
/// biblioteca de terceros filtraría detalles y rutas.
#[derive(Debug, Serialize, TS)]
#[ts(export, export_to = "../../src/lib/bindings/")]
pub struct NsErrorPayload {
    pub code: String,
}

impl serde::Serialize for NsError {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        NsErrorPayload {
            code: self.code().to_owned(),
        }
        .serialize(serializer)
    }
}

/// Resultado de toda la superficie pública del runtime.
pub type NsResult<T> = std::result::Result<T, NsError>;

#[cfg(test)]
mod tests {
    use super::*;

    /// Copia deliberadamente independiente de [`NsError::code`]: si la prueba
    /// llamara a `code()`, renombrar un código pasaría en verde. El `match` es
    /// exhaustivo, así que una variante nueva no compila sin decidir su código.
    fn codigo_esperado(error: &NsError) -> &'static str {
        match error {
            NsError::FileNotFound => "FILE_NOT_FOUND",
            NsError::PathNotAllowed => "PATH_NOT_ALLOWED",
            NsError::FormatUnsupported => "FORMAT_UNSUPPORTED",
            NsError::AudioCorrupted => "AUDIO_CORRUPTED",
            NsError::StorageFailure => "STORAGE_FAILURE",
            NsError::SchemaMismatch => "SCHEMA_MISMATCH",
            NsError::ComponentUnavailable => "COMPONENT_UNAVAILABLE",
            NsError::NetworkDisabled => "NETWORK_DISABLED",
            NsError::ConsentRequired => "CONSENT_REQUIRED",
            NsError::NetworkFailure => "NETWORK_FAILURE",
            NsError::IntegrityMismatch => "INTEGRITY_MISMATCH",
            NsError::AddonRequired => "ADDON_REQUIRED",
            NsError::Cancelled => "CANCELLED",
            NsError::InvalidInput => "INVALID_INPUT",
            NsError::NameTaken => "NAME_TAKEN",
            NsError::Internal => "INTERNAL",
        }
    }

    #[test]
    fn los_codigos_son_estables() {
        assert_eq!(TODAS.len(), 16, "hay una variante fuera de la lista");
        for variante in TODAS {
            assert_eq!(variante.code(), codigo_esperado(variante));
        }
    }

    #[test]
    fn los_codigos_son_unicos_y_canonicos() {
        let codigos: std::collections::BTreeSet<_> = TODAS.iter().map(NsError::code).collect();
        assert_eq!(codigos.len(), TODAS.len(), "hay códigos repetidos");
        for codigo in &codigos {
            assert!(codigo.chars().all(|c| c.is_ascii_uppercase() || c == '_'));
        }
    }

    #[test]
    fn se_serializa_solo_el_codigo() {
        let json = serde_json::to_string(&NsError::AudioCorrupted).expect("serializable");
        assert_eq!(json, r#"{"code":"AUDIO_CORRUPTED"}"#);
    }
}
